-- 1. LIMPIEZA DE TABLAS (Opcional, en orden inverso por dependencias de FK)
DROP TABLE IF EXISTS notificaciones CASCADE;
DROP TABLE IF EXISTS recetas CASCADE;
DROP TABLE IF EXISTS atenciones CASCADE;
DROP TABLE IF EXISTS citas CASCADE;
DROP TABLE IF EXISTS turnos CASCADE;
DROP TABLE IF EXISTS medicos CASCADE;
DROP TABLE IF EXISTS pacientes CASCADE;
DROP TABLE IF EXISTS especialidades CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;

-- =====================================================================
-- 2. DEFINICIÓN DE TABLAS (DDL)
-- =====================================================================

-- 2.1. Tabla: usuarios
CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(20) NOT NULL UNIQUE,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('ADMIN', 'RECEPCION', 'MEDICO'))
);

-- 2.2. Tabla: especialidades
CREATE TABLE especialidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500)
);

-- 2.3. Tabla: medicos
CREATE TABLE medicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE,
    especialidad_id BIGINT NOT NULL,
    colegiatura VARCHAR(30) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_medicos_usuarios FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE CASCADE,
    CONSTRAINT fk_medicos_especialidades FOREIGN KEY (especialidad_id) REFERENCES especialidades (id)
);

-- 2.4. Tabla: pacientes
CREATE TABLE pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni VARCHAR(20) NOT NULL UNIQUE,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE,
    telefono VARCHAR(20),
    email VARCHAR(150),
    direccion VARCHAR(255)
);

-- 2.5. Tabla: turnos
CREATE TABLE turnos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id BIGINT NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fin TIMESTAMP NOT NULL,
    version BIGINT DEFAULT 0,
    CONSTRAINT fk_turnos_medicos FOREIGN KEY (medico_id) REFERENCES medicos (id) ON DELETE CASCADE
);

-- 2.6. Tabla: citas
CREATE TABLE citas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    turno_id BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'RESERVADA' CHECK (estado IN ('RESERVADA', 'CANCELADA', 'ATENDIDA', 'AUSENTE')),
    motivo VARCHAR(500),
    creada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_citas_pacientes FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT fk_citas_turnos FOREIGN KEY (turno_id) REFERENCES turnos (id)
);

-- 2.7. Tabla: atenciones
CREATE TABLE atenciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id BIGINT NOT NULL UNIQUE,
    medico_usuario_id BIGINT NOT NULL,
    codigo_cie10 VARCHAR(10) NOT NULL,
    motivo_consulta VARCHAR(2000) NOT NULL,
    diagnostico VARCHAR(4000) NOT NULL,
    notas VARCHAR(6000),
    creada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_atenciones_citas FOREIGN KEY (cita_id) REFERENCES citas (id),
    CONSTRAINT fk_atenciones_usuarios FOREIGN KEY (medico_usuario_id) REFERENCES usuarios (id)
);

-- 2.8. Tabla: recetas
CREATE TABLE recetas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atencion_id BIGINT NOT NULL,
    medicamento VARCHAR(200) NOT NULL,
    dosis VARCHAR(200) NOT NULL,
    indicaciones VARCHAR(500) NOT NULL,
    duracion VARCHAR(100),
    CONSTRAINT fk_recetas_atenciones FOREIGN KEY (atencion_id) REFERENCES atenciones (id) ON DELETE CASCADE
);

-- 2.9. Tabla: notificaciones
CREATE TABLE notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('CONFIRMACION', 'RECORDATORIO', 'REPROGRAMACION', 'CANCELACION')),
    destinatario VARCHAR(300) NOT NULL,
    mensaje VARCHAR(1000) NOT NULL,
    estado_entrega VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA' CHECK (estado_entrega IN ('REGISTRADA', 'ENVIADA', 'SIN_CORREO', 'ERROR')),
    creada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notificaciones_citas FOREIGN KEY (cita_id) REFERENCES citas (id) ON DELETE CASCADE
);

-- =====================================================================
-- 3. ÍNDICES RECOMENDADOS (Para optimización de consultas comunes)
-- =====================================================================
CREATE INDEX idx_turnos_medico ON turnos(medico_id);
CREATE INDEX idx_turnos_inicio_fin ON turnos(inicio, fin);
CREATE INDEX idx_citas_paciente ON citas(paciente_id);
CREATE INDEX idx_citas_turno ON citas(turno_id);
CREATE INDEX idx_citas_estado ON citas(estado);
CREATE INDEX idx_notificaciones_cita ON notificaciones(cita_id);

